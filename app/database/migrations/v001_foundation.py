"""M2 foundation. Immutable once released; changes require a new version."""

STATEMENTS = (
    """CREATE TABLE settings (
        key TEXT PRIMARY KEY NOT NULL,
        value TEXT NOT NULL,
        updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
    )""",
    """CREATE TABLE sources (
        source_id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        root_path TEXT NOT NULL UNIQUE,
        volume_identifier TEXT,
        current_mount TEXT,
        enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
        online INTEGER NOT NULL DEFAULT 0 CHECK(online IN (0,1)),
        last_scan TEXT,
        watch_enabled INTEGER NOT NULL DEFAULT 0 CHECK(watch_enabled IN (0,1)),
        created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
        updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
    )""",
    """CREATE TABLE assets (
        asset_id INTEGER PRIMARY KEY AUTOINCREMENT,
        source_id INTEGER NOT NULL REFERENCES sources(source_id) ON DELETE RESTRICT,
        absolute_path TEXT NOT NULL UNIQUE,
        relative_path TEXT NOT NULL,
        filename TEXT NOT NULL,
        extension TEXT NOT NULL,
        media_type TEXT NOT NULL CHECK(media_type IN ('image','video')),
        file_size INTEGER CHECK(file_size >= 0),
        created_time TEXT,
        modified_time TEXT,
        indexed_time TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
        width INTEGER CHECK(width > 0),
        height INTEGER CHECK(height > 0),
        aspect_ratio REAL CHECK(aspect_ratio > 0),
        duration REAL CHECK(duration >= 0),
        fps REAL CHECK(fps >= 0),
        video_codec TEXT,
        audio_codec TEXT,
        quick_hash TEXT,
        content_hash TEXT,
        thumbnail_path TEXT,
        poster_path TEXT,
        preview_proxy_path TEXT,
        rating INTEGER NOT NULL DEFAULT 0 CHECK(rating BETWEEN 0 AND 5),
        favorite INTEGER NOT NULL DEFAULT 0 CHECK(favorite IN (0,1)),
        missing INTEGER NOT NULL DEFAULT 0 CHECK(missing IN (0,1)),
        managed INTEGER NOT NULL DEFAULT 0 CHECK(managed IN (0,1)),
        created_by_comfyui INTEGER NOT NULL DEFAULT 0 CHECK(created_by_comfyui IN (0,1))
    )""",
    "CREATE INDEX idx_assets_source_id ON assets(source_id)",
    "CREATE INDEX idx_assets_filename ON assets(filename)",
    "CREATE INDEX idx_assets_media_type ON assets(media_type)",
    "CREATE INDEX idx_assets_modified_time ON assets(modified_time)",
    "CREATE INDEX idx_assets_content_hash ON assets(content_hash) WHERE content_hash IS NOT NULL",
    "CREATE INDEX idx_assets_missing ON assets(missing)",
    "CREATE INDEX idx_assets_managed ON assets(managed)",
)
